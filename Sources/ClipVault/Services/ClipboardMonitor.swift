import AppKit

/// Watches the general pasteboard and reports new text and images.
///
/// macOS has no pasteboard change notification, so this polls `changeCount`,
/// which is a cheap integer read.
final class ClipboardMonitor {
    static let maxTextLength = 1_000_000
    static let maxImageBytes = 25 * 1024 * 1024

    /// Types that password managers and other apps set to say "don't record this".
    /// See http://nspasteboard.org.
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    private static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png, .tiff, NSPasteboard.PasteboardType("public.jpeg"), NSPasteboard.PasteboardType("public.heic"),
    ]

    var shouldCapture: (SourceApp?) -> Bool = { _ in true }
    var onCapture: (CapturedContent, SourceApp?) -> Void = { _, _ in }

    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private var timer: Timer?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        // Whatever is on the clipboard at launch was already there; don't record it.
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Puts an item back on the pasteboard without recording it again.
    @discardableResult
    func write(_ item: ClipItem, imageData: Data?) -> Bool {
        switch item.content {
        case .text(let text):
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
        case .image:
            guard let imageData else { return false }
            pasteboard.clearContents()
            pasteboard.setData(imageData, forType: .png)
            if let tiff = NSBitmapImageRep(data: imageData)?.tiffRepresentation {
                pasteboard.setData(tiff, forType: .tiff)
            }
        }
        lastChangeCount = pasteboard.changeCount
        return true
    }

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        let source = NSWorkspace.shared.frontmostApplication.map {
            SourceApp(bundleID: $0.bundleIdentifier, name: $0.localizedName)
        }
        guard shouldCapture(source),
              let types = pasteboard.types,
              !Self.containsSensitiveType(types),
              let content = Self.read(from: pasteboard, types: types)
        else { return }
        onCapture(content, source)
    }

    static func containsSensitiveType(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        types.contains { sensitiveTypes.contains($0.rawValue) }
    }

    /// Text wins unless the pasteboard's preferred (first) representation is an image:
    /// office apps put image renderings next to copied text, while "Copy Image" and
    /// screenshots lead with the image.
    private static func read(from pasteboard: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> CapturedContent? {
        let isFile = types.contains(.fileURL)
        let leadsWithImage = types.first.map(imageTypes.contains) ?? false

        if leadsWithImage, !isFile, let image = readImage(from: pasteboard, types: types) {
            return image
        }
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(String(text.prefix(maxTextLength)))
        }
        return isFile ? nil : readImage(from: pasteboard, types: types)
    }

    private static func readImage(from pasteboard: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> CapturedContent? {
        for type in imageTypes where types.contains(type) {
            guard let data = pasteboard.data(forType: type), data.count <= maxImageBytes,
                  let bitmap = NSBitmapImageRep(data: data)
            else { continue }
            let png = type == .png ? data : bitmap.representation(using: .png, properties: [:])
            guard let png, png.count <= maxImageBytes else { continue }
            return .image(png: png, width: bitmap.pixelsWide, height: bitmap.pixelsHigh)
        }
        return nil
    }
}
